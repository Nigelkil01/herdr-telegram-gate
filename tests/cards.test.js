'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const vm = require('vm');
const { createRequire } = require('module');
const root = fs.mkdtempSync(path.join(process.env.TMPDIR || os.tmpdir(), 'gate-cards-'));
fs.copyFileSync(path.join(__dirname, '../policy.json'), path.join(root, 'policy.json'));
const fixture = fs.readFileSync(path.join(__dirname, 'fixtures/codex-approval.txt'), 'utf8');
const source = fs.readFileSync(path.join(__dirname, '../bot.js'), 'utf8')
  .replace('const ROOT = __dirname;', `const ROOT = ${JSON.stringify(root)};`)
  .replace("const { classify } = require('./research/classify.js');", `const { classify } = require(${JSON.stringify(path.join(__dirname, '../research/classify.js'))});`)
  .replace(/main\(\)\.catch\(e => \{[\s\S]*?\}\);\s*$/, `
    herdrAgentGet = async () => ({agent:'codex',display_agent:'agent · working',name:'worker',title:'HTRG-1 test',pane_id:'w1:p1',cwd:'/tmp',agent_status:globalThis.agentStatus || 'blocked',agent_session:globalThis.session || null,state_change_seq:globalThis.seq});
    herdrAgentRead = async () => {if (globalThis.failRead) throw new Error('offline'); return globalThis.fixture};
    tgSendMessage = async (text) => {globalThis.sent = text; return {message_id:1}};
    tgAnswerCallback = async () => {};
    tgEditMessage = async () => {};
    herdrAgentSendKeys = async (pane, key) => {globalThis.keyCount++; globalThis.keys.push(key)};
    globalThis.api = {handleBlocked, executeCallback, handleCallbackQuery, requestScreen, approvalMessage};`);
const proc = {...process, env:{...process.env, TELEGRAM_OWNER_ID:'123'}};
const ctx = { require: createRequire(path.join(__dirname, '../bot.js')), process:proc, console, __dirname:root, setTimeout, Buffer, fixture, keyCount:0, keys:[], seq:1 };
vm.runInNewContext(source, ctx);
(async () => {
  await ctx.api.handleBlocked('w1:p1');
  assert.match(ctx.sent, /codex/);
  assert.match(ctx.sent, /HTRG-1/);
  assert.match(ctx.sent, /\$ ls \/tmp/);
  const id = Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending)[0];
  const commandIndex = fixture.lastIndexOf('ls /tmp');
  ctx.fixture = fixture.slice(0, commandIndex) + 'pwd' + fixture.slice(commandIndex + 'ls /tmp'.length);
  await ctx.api.executeCallback({id:'tap',from:{id:123},message:{chat:{id:123},message_id:1},data:`app:${id}`}, 'approve');
  assert.equal(ctx.keyCount, 0, 'changed screen never presses keys');
  assert.equal(Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending).length, 0);
  await ctx.api.handleBlocked('w1:p1');
  assert.equal(Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending).length, 1, 'changed request can produce a replacement without a new sequence');
  ctx.fixture = fixture;
  ctx.seq++;
  await ctx.api.handleBlocked('w1:p1');
  const approved = Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending)[0];
  await ctx.api.executeCallback({id:'tap2',from:{id:123},message:{chat:{id:123},message_id:2},data:`app:${approved}`}, 'approve');
  assert.equal(ctx.keyCount, 1, 'unchanged screen accepts one approval');
  assert.equal(Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending).length, 0, 'approved entry is removed');
  ctx.seq++;
  await ctx.api.handleBlocked('w1:p1');
  const denied = Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending)[0];
  await ctx.api.executeCallback({id:'tap3',from:{id:123},message:{chat:{id:123},message_id:3},data:`den:${denied}`}, 'deny');
  assert.equal(ctx.keyCount, 2, 'denial sends one key');
  assert.equal(Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending).length, 0, 'denied entry is removed');
  const claude = fs.readFileSync(path.join(__dirname, 'fixtures/claude-approval-unverified.txt'), 'utf8');
  assert.match(ctx.api.requestScreen(claude), /printf hello/);
  const question = 'Do you want to continue with this approach?\n\n❯ Yes\n  No';
  assert.equal(ctx.api.requestScreen(question), question);
  assert.match(ctx.api.approvalMessage({agent:'codex',pane_id:'p',task_id:'HTRG-1',screen:question,tier:2,expires_at:new Date().toISOString()}), /Do you want to continue with this approach/);
  const card = screen => ctx.api.approvalMessage({agent:'codex',pane_id:'p',screen,tier:2,expires_at:new Date().toISOString()});
  const secret = 'FAKEKEYBODY'.repeat(250);
  assert.doesNotMatch(card(`-----BEGIN RSA PRIVATE KEY-----\n${secret}\n-----END RSA PRIVATE KEY-----\n${question}`), /FAKEKEYBODY/);
  assert.doesNotMatch(card(`-----BEGIN RSA PRIVATE KEY-----\n${secret}`), /FAKEKEYBODY/);
  for (const label of ['PRIVATE KEY', 'RSA PRIVATE KEY', 'EC PRIVATE KEY', 'OPENSSH PRIVATE KEY']) {
    const complete = card(`-----BEGIN ${label}-----\n${secret}\n-----END ${label}-----\n${question}`);
    assert.doesNotMatch(complete, /FAKEKEYBODY/, `${label}: complete key body is redacted`);
    assert.match(complete, /Do you want to continue with this approach\?/, `${label}: question survives redaction`);
    const command = 'Would you like to run the following command?\n$ ls /tmp';
    const withCommand = card(`-----BEGIN ${label}-----\n${secret}\n-----END ${label}-----\n${command}`);
    assert.doesNotMatch(withCommand, /FAKEKEYBODY/);
    assert.match(withCommand, /\$ ls \/tmp/, `${label}: command survives redaction`);
    const incomplete = card(`${question}\n-----BEGIN ${label}-----\n${secret}`);
    assert.doesNotMatch(incomplete, /FAKEKEYBODY/, `${label}: unterminated key body is redacted`);
    assert.match(incomplete, /Do you want to continue with this approach\?/, `${label}: preceding question survives redaction`);
  }
  assert.match(card('older transcript\n'.repeat(300) + question), /Do you want to continue with this approach/);
  ctx.fixture = fixture;
  ctx.seq++;
  await ctx.api.handleBlocked('w1:p1');
  const stable = Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending)[0];
  ctx.fixture = fixture.replace('OpenAI Codex', 'OpenAI Codex ');
  await ctx.api.executeCallback({id:'tap4',from:{id:123},message:{chat:{id:123},message_id:4},data:`app:${stable}`}, 'approve');
  assert.equal(ctx.keyCount, 3, 'irrelevant banner change does not invalidate request');
  const pending = () => Object.keys(JSON.parse(fs.readFileSync(path.join(root, 'state.json'))).pending)[0];
  const tap = (id, prefix) => ctx.api.handleCallbackQuery({id:'tap-route',from:{id:123},message:{chat:{id:123},message_id:5},data:`${prefix}:${id}`});
  ctx.fixture = fixture; ctx.seq++;
  await ctx.api.handleBlocked('w1:p1');
  const staleDeny = pending();
  ctx.fixture = fixture.slice(0, commandIndex) + 'pwd' + fixture.slice(commandIndex + 'ls /tmp'.length);
  await tap(staleDeny, 'den');
  assert.equal(ctx.keyCount, 3, 'stale Deny must not send Escape to a changed request');
  ctx.fixture = fixture; ctx.seq++;
  await ctx.api.handleBlocked('w1:p1');
  const staleSession = pending();
  ctx.session = {id:'replacement'};
  await tap(staleSession, 'den');
  assert.equal(ctx.keyCount, 3, 'stale Deny must not send Escape to a replaced session');
  ctx.session = null; ctx.seq++;
  await ctx.api.handleBlocked('w1:p1');
  const sameScreenNewRequest = pending();
  ctx.seq++;
  await tap(sameScreenNewRequest, 'app');
  assert.equal(ctx.keyCount, 3, 'old Approve must not accept a new request with the same screen');
  await ctx.api.handleBlocked('w1:p1');
  const validDeny = pending();
  await tap(validDeny, 'den');
  assert.deepEqual(ctx.keys, ['Enter', 'esc', 'Enter', 'esc'], 'current Deny still sends Escape');
  ctx.seq++;
  await ctx.api.handleBlocked('w1:p1');
  const noLongerBlocked = pending();
  ctx.agentStatus = 'working';
  await tap(noLongerBlocked, 'den');
  assert.equal(ctx.keyCount, 4, 'Deny does not press keys if the agent is no longer blocked');
  ctx.agentStatus = 'blocked'; ctx.seq++;
  await ctx.api.handleBlocked('w1:p1');
  const unreadable = pending();
  ctx.failRead = true;
  await tap(unreadable, 'den');
  assert.equal(ctx.keyCount, 4, 'Deny fails closed when the pane cannot be read');
  ctx.failRead = false;
  await tap(unreadable, 'den');
  assert.equal(ctx.keys[4], 'esc', 'Deny can be retried after a transient read failure');
  console.log('captured approval card and reconstructed question passed');
})().catch(e => { console.error(e); process.exitCode = 1; });
